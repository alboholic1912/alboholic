const TYPES_WITH_IMAGE = new Set(["stories", "people", "battles"]);

// The AI image is generated by a Server Action on this page, and image models can take one to
// two minutes. Server Actions take their time limit from the page, so raise it from the default.
export const maxDuration = 300;

export async function generateMetadata({
  params,
}: PageProps<"/kalaja-cabb0da6/[type]/[id]">): Promise<Metadata> {
  const { type } = await params;
  const config = isContentType(type) ? CONTENT_CONFIG[type] : null;
  return {
    title: config ? `Edit ${config.label} — Studio` : "Studio",
    robots: { index: false, follow: false },
  };
}

export default async function EditContentPage({
  params,
  searchParams,
}: PageProps<"/kalaja-cabb0da6/[type]/[id]">) {
  await requireUser();

  const { type, id } = await params;
  if (!isContentType(type)) notFound();
  const config = CONTENT_CONFIG[type];
  const { imageError } = await searchParams;

  const item = await getContentById(type, id);
  if (!item) notFound();

  const record = item as unknown as Record<string, unknown>;
  const sources = (record.sources as SourceRecord[] | undefined) ?? [];
  const hasImage = TYPES_WITH_IMAGE.has(type);
  const imageJob = hasImage ? await getLatestImageJob(type, id) : null;

  return (
    <div className={styles.wrap}>
      <div className={styles.backRow}>
        <BackLink href={`/kalaja-cabb0da6/${type}`} label={config.labelPlural} />
      </div>

      <div className={styles.toolbar}>
        <h1 className={styles.title}>{String(record[config.titleField] ?? "Untitled")}</h1>
        <span
          className={`${styles.badge} ${
            record.status === "published" ? styles.badgePublished : styles.badgeReview
          }`}
        >
          {String(record.status)}
        </span>
      </div>

      {sources.length > 0 && (
        <div className={styles.section} style={{ marginBottom: "var(--space-6)" }}>
          <div className={styles.sectionTitle}>Sources used to generate this</div>
          <ul style={{ paddingLeft: "1.2em", color: "var(--color-text-muted)", fontSize: "0.9rem" }}>
            {sources.map((source, i) => (
              <li key={i}>
                {source.kind === "text" && <>Pasted text — &ldquo;{source.preview}&rdquo;&hellip;</>}
                {source.kind === "youtube" && <>YouTube — {source.url}</>}
                {source.kind === "file" && <>File — {source.name}</>}
              </li>
            ))}
          </ul>
        </div>
      )}

      {hasImage && (
        <AiImageSection
          type={type}
          id={id}
          job={imageJob}
          error={typeof imageError === "string" ? imageError : undefined}
        />
      )}

      <form action={updateContent} className={styles.form}>
        <input type="hidden" name="type" value={type} />
        <input type="hidden" name="id" value={id} />

        {hasImage && (
          <div className={styles.field}>
            <label htmlFor="image">Featured image</label>
            {typeof record.image === "string" && record.image ? (
              <Image src={record.image} alt="" width={280} height={180} className={styles.thumb} unoptimized />
            ) : (
              <p className={styles.help}>No image uploaded yet.</p>
            )}
            <input id="image" type="file" name="image" accept="image/*" />
            <span className={styles.help}>
              Choose a file, then click &ldquo;Save changes&rdquo; below to upload it.
            </span>
          </div>
        )}

        <div className={styles.field}>
          <label htmlFor="slug">Slug</label>
          <input id="slug" name="slug" type="text" defaultValue={item.slug} />
        </div>

        {config.fields.map((field) => renderField(field, record))}

        <div className={styles.actions}>
          <SubmitButton
            className={`${styles.button} ${styles.buttonPrimary}`}
            pendingText="Saving…"
          >
            Save changes
          </SubmitButton>
        </div>
      </form>

      <div className={styles.actions} style={{ marginTop: "var(--space-6)" }}>
        {record.status === "published" ? (
          <form action={unpublishContent}>
            <input type="hidden" name="type" value={type} />
            <input type="hidden" name="id" value={id} />
            <SubmitButton className={styles.button} pendingText="Unpublishing…">
              Unpublish
            </SubmitButton>
          </form>
        ) : (
          <form action={publishContent}>
            <input type="hidden" name="type" value={type} />
            <input type="hidden" name="id" value={id} />
            <SubmitButton
              className={`${styles.button} ${styles.buttonPrimary}`}
              pendingText="Publishing…"
            >
              Publish to site
            </SubmitButton>
          </form>
        )}
        <form action={deleteContent}>
          <input type="hidden" name="type" value={type} />
          <input type="hidden" name="id" value={id} />
          <SubmitButton
            className={`${styles.button} ${styles.buttonDanger}`}
            pendingText="Deleting…"
          >
            Delete
          </SubmitButton>
        </form>
      </div>
    </div>
  );
}

function AiImageSection({
  type,
  id,
  job,
  error,
}: {
  type: ContentType;
  id: string;
  job: ImageJob | null;
  error?: string;
}) {
  const running = job?.status === "pending" || job?.status === "generating";
  const failure = job?.status === "failed" ? job.error : null;

  return (
    <div className={styles.section} style={{ marginBottom: "var(--space-6)", maxWidth: 760 }}>
      <div className={styles.sectionTitle}>AI image</div>

      {error && <div className={styles.error}>{error}</div>}
      {failure && <div className={styles.error}>Image generation failed: {failure}</div>}

      {job && (
        <div style={{ display: "flex", gap: "var(--space-4)", flexWrap: "wrap", alignItems: "flex-start" }}>
          <div className={styles.field}>
            <span className={styles.fieldLabel}>Reference</span>
            <Image src={mediaUrl(job.reference_path)} alt="" width={160} height={120} className={styles.thumb} style={{ objectFit: "cover" }} unoptimized />
          </div>
          {job.status === "done" && job.image && (
            <div className={styles.field}>
              <span className={styles.fieldLabel}>Last result ({IMAGE_MODE_LABELS[job.mode]})</span>
              <Image src={job.image} alt="" width={160} height={120} className={styles.thumb} style={{ objectFit: "cover" }} unoptimized />
            </div>
          )}
        </div>
      )}

      {running && job ? (
        <ImageJobRunner jobId={job.id} status={job.status as "pending" | "generating"} className={styles.help} />
      ) : (
        <form action={regenerateImage} className={styles.form} style={{ gap: "var(--space-4)" }}>
          <input type="hidden" name="type" value={type} />
          <input type="hidden" name="id" value={id} />
          <ImagePromptFields
            fieldClassName={styles.field}
            helpClassName={styles.help}
            defaultMode={job?.mode}
            defaultPrompt={job?.prompt}
            referenceHelp={
              job
                ? "Optional. Leave it empty to reuse the reference shown above."
                : "PNG, JPEG or WebP. The result replaces the featured image."
            }
          />
          <div className={styles.actions}>
            <SubmitButton className={`${styles.button} ${styles.buttonPrimary}`} pendingText="Starting…">
              {job ? "Regenerate image" : "Generate image"}
            </SubmitButton>
          </div>
        </form>
      )}
    </div>
  );
}

function toCoordinate(value: unknown): number | null {
  return typeof value === "number" && Number.isFinite(value) ? value : null;
}

function renderField(field: FieldDef, record: Record<string, unknown>) {
  const value = record[field.key];

  if (field.kind === "checkbox") {
    return (
      <div key={field.key} className={`${styles.field} ${styles.checkboxField}`}>
        <input id={field.key} name={field.key} type="checkbox" defaultChecked={Boolean(value)} />
        <label htmlFor={field.key}>{field.label}</label>
      </div>
    );
  }

  if (field.kind === "select") {
    const current = String(value ?? "");
    const options = field.options ?? [];
    return (
      <div key={field.key} className={styles.field}>
        <label htmlFor={field.key}>{field.label}</label>
        <select id={field.key} name={field.key} defaultValue={current}>
          {/* Keep a value the options don't cover (e.g. not set yet) instead of silently replacing it on save. */}
          {!options.includes(current) && <option value={current}>{current || "Not set"}</option>}
          {options.map((option) => (
            <option key={option} value={option}>
              {option}
            </option>
          ))}
        </select>
        {field.helpText && <span className={styles.help}>{field.helpText}</span>}
      </div>
    );
  }

  if (field.kind === "paragraphs") {
    const text = Array.isArray(value) ? value.join("\n") : "";
    return (
      <div key={field.key} className={styles.field}>
        <label htmlFor={field.key}>{field.label}</label>
        <textarea id={field.key} name={field.key} rows={field.rows ?? 12} defaultValue={text} />
        {field.helpText && <span className={styles.help}>{field.helpText}</span>}
      </div>
    );
  }

  if (field.kind === "records") {
    return (
      <div key={field.key} className={styles.field}>
        <label htmlFor={field.key}>{field.label}</label>
        <textarea
          id={field.key}
          name={field.key}
          rows={field.rows ?? 8}
          defaultValue={formatRecordLines(value, field.columns ?? [])}
        />
        {field.helpText && <span className={styles.help}>{field.helpText}</span>}
      </div>
    );
  }

  if (field.kind === "coordinates") {
    return (
      <div key={field.key} className={styles.field}>
        <span className={styles.fieldLabel}>{field.label}</span>
        <LocationPicker lat={toCoordinate(record.lat)} lng={toCoordinate(record.lng)} />
        {field.helpText && <span className={styles.help}>{field.helpText}</span>}
      </div>
    );
  }

  if (field.kind === "textarea") {
    return (
      <div key={field.key} className={styles.field}>
        <label htmlFor={field.key}>{field.label}</label>
        <textarea id={field.key} name={field.key} rows={field.rows ?? 4} defaultValue={String(value ?? "")} />
        {field.helpText && <span className={styles.help}>{field.helpText}</span>}
      </div>
    );
  }

  if (field.kind === "number") {
    return (
      <div key={field.key} className={styles.field}>
        <label htmlFor={field.key}>{field.label}</label>
        <input id={field.key} name={field.key} type="number" defaultValue={Number(value ?? 0)} />
        {field.helpText && <span className={styles.help}>{field.helpText}</span>}
      </div>
    );
  }

  return (
    <div key={field.key} className={styles.field}>
      <label htmlFor={field.key}>{field.label}</label>
      <input id={field.key} name={field.key} type="text" defaultValue={String(value ?? "")} />
      {field.helpText && <span className={styles.help}>{field.helpText}</span>}
    </div>
  );
}
